def parse_args():
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", required=True, help="Path to uncalibrated CSV")
    ap.add_argument("--output", required=True, help="Path to calibrated CSV output")
    ap.add_argument("--params", required=True, help="Path to write calibration_params.json")
    ap.add_argument("--timecol", default=None, help="Optional name of timestamp column")
    ap.add_argument("--compute_allan", action="store_true", help="Compute Allan deviation for gyro")
    return ap.parse_args()

if __name__ == "__main__":
    args = parse_args()
    run_calibration(args.input, args.output, args.params,
                    timecol=args.timecol, compute_allan=args.compute_allan)